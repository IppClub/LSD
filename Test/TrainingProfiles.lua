-- Real DB isolation between learned actors, with legacy Ni rows unchanged.
local D=require("Dora")
local root=D.Path:getPath(D.Path:getScriptPath(...)); D.Content:insertSearchPath(1,D.Path(root,"Script"))
local id=tostring(os.time()); local out=D.Path(root,"Test","training-profiles-result.txt"); D.Content:save(out,"LSD_TRAINING_PROFILES_RUNNING runId="..id.."\n")
local db=D.Path(D.Content.writablePath,"lsd-training-profiles-qa-"..id..".db")
assert(not D.DB:existDB("lsd") and not D.Content:exist(db) and D.DB:exec("ATTACH DATABASE '"..db:gsub("'","''").."' AS lsd")>=0)
D.Director.entry:slot("Cleanup",function() if D.DB:existDB("lsd") then D.DB:exec("DETACH DATABASE lsd") end end)
D.thread(function()
 local ok,result=xpcall(function()
  local Store=require("Training.Store"); local Progress=require("Training.Progress")
  local function model(id,action) return {schemaVersion=1,featureSchemaVersion=2,actionSetVersion=1,characterId=id,actions=require("Training.Characters")[id].actions,sampleCount=7,trainingAccuracy=1,rules={{conditions={},action=action}}} end
  local ni=assert(Store.open()); ni:load(); assert(ni:saveAsync(model("ninilite","laser")))
  local niPayload=D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='main'")[1][1]
  local w=assert(Store.open(nil,"wuyun")); local missing,state=w:load(); assert(not missing and state=="NEW_PROFILE")
  assert(not w:saveAsync(model("ninilite","laser")),"Cross character saved")
  assert(w:saveAsync(model("wuyun","melee"))); assert(w:saveAsync(model("wuyun","laser"),model("wuyun","melee")))
  assert(D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='main'")[1][1]==niPayload)
  assert(Progress.load() and Progress.adopted.characterId=="ninilite")
  local wp=Progress.forCharacter("wuyun"); assert(wp.load() and wp.adopted.rules[1].action=="laser" and wp.previous.rules[1].action=="melee")
  assert(Progress.adopted.characterId=="ninilite" and wp~=Progress)
  local backup=D.DB:query("SELECT payload FROM lsd.Game0Training_wuyun WHERE slot='backup'")[1][1]
  assert(D.DB:exec("CREATE TRIGGER lsd.fail_wuyun_write BEFORE INSERT ON Game0Training_wuyun WHEN NEW.slot='main' BEGIN SELECT RAISE(ABORT,'QA Wuyun fault'); END")>=0)
  assert(not wp.saveAsync(model("wuyun","fmove"),wp.adopted))
  assert(wp.adopted.rules[1].action=="laser" and D.DB:query("SELECT payload FROM lsd.Game0Training_wuyun WHERE slot='backup'")[1][1]==backup)
  D.DB:exec("DROP TRIGGER lsd.fail_wuyun_write")
  D.DB:exec("UPDATE lsd.Game0Training_wuyun SET payload='{broken' WHERE slot='main'")
  assert(wp.load() and wp.status=="RECOVERED_BACKUP" and wp.adopted.rules[1].action=="melee")
  assert(wp.saveAsync(model("wuyun","idle"),wp.adopted))
  assert(D.DB:query("SELECT payload FROM lsd.Game0Training_wuyun WHERE slot='quarantine'")[1][1]=="{broken")
  local future=model("wuyun","melee"); future.featureSchemaVersion=99
  local payload=D.json.encode({schemaVersion=1,characterId="wuyun",revision=9,adopted=model("wuyun","laser"),previous=future})
  assert(D.DB:exec("UPDATE lsd.Game0Training_wuyun SET payload=? WHERE slot='main'",{{payload}})>=0)
  assert(not wp.load() and wp.status=="INCOMPATIBLE_SAVE_READ_ONLY" and not wp.saveAsync(model("wuyun","idle")))
  assert(D.DB:query("SELECT payload FROM lsd.Game0Training_wuyun WHERE slot='main'")[1][1]==payload)
  assert(D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='main'")[1][1]==niPayload and Progress.load())
  assert(not Store.open(nil,"unknown"))
  return "PASS separateActors=true legacyNiUntouched=true crossCharacterRejected=true independentPrevious=true atomicWuyunFailure=true isolatedBackup=true quarantine=true futurePreviousReadOnly=true NiStillWritable=true unknownRejected=true"
 end,debug.traceback)
 local report="LSD_TRAINING_PROFILES_"..(ok and result or "FAIL "..tostring(result)).." runId="..id; print(report); D.Content:save(out,report.."\n")
end)
