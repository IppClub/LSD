-- After actual native restart: independent learners and their saved real trees.
local D=require("Dora")
local root=D.Path:getPath(D.Path:getScriptPath(...))
for _,p in ipairs({root,D.Path(root,"Script"),D.Path(root,"Spine"),D.Path(root,"Image"),D.Path(root,"Font")}) do D.Content:insertSearchPath(1,p) end
local id=tostring(os.time()); local out=D.Path(root,"Test","wuyun-training-resume-result.txt"); D.Content:save(out,"LSD_WUYUN_RESUME_RUNNING runId="..id.."\n")
D.thread(function()
 local ok,result=xpcall(function()
  local db=assert(D.Content:load(D.Path(root,"Test","wuyun-training-resume-fixture.txt")))
  assert(D.Path:getPath(db)==D.Content.writablePath and D.Path:getFilename(db):match("^lsd%-wuyun%-training%-qa%-%d+%.db$"))
  assert(not D.DB:existDB("lsd") and D.DB:exec("ATTACH DATABASE '"..db:gsub("'","''").."' AS lsd")>=0)
  D.Director.entry:slot("Cleanup",function() if D.DB:existDB("lsd") then D.DB:exec("DETACH DATABASE lsd") end end)
  require("Start")
  local function wait(f,t) local deadline=D.App.runningTime+(t or 15); while not f() do assert(D.App.runningTime<deadline,"Wuyun resume timed out"); D.sleep(0.05) end end
  wait(function() local w=D.Platformer.Data.store.world; return w and w.tag=="PreparationRoom" end)
  wait(function() local w=D.Platformer.Data.store.world; local e=D.Group({"player","unit"}):find(function(e) return e.player and e.unit.world==w end); return e and not e.busy end)
  local Progress=require("Training.Progress"); local wp=Progress.forCharacter("wuyun")
  assert(Progress.load() and Progress.adopted.characterId=="ninilite" and Progress.adopted.sampleCount==6)
  assert(wp.load() and wp.adopted.characterId=="wuyun" and wp.adopted.sampleCount==18)
  local niBefore=D.json.encode(D.DB:query("SELECT slot,payload FROM lsd.Game0Training ORDER BY slot"),false,true)
  local wBefore=D.json.encode(D.DB:query("SELECT slot,payload FROM lsd.Game0Training_wuyun ORDER BY slot"),false,true)
  assert(require("Story.Service").open():summary().completed["energy-plan"])
  require("Academy.Navigation").returnToTrainingAsync()
  local world=D.Platformer.Data.store.world
  local function player() return D.Group({"player","unit"}):find(function(e) return e.player and e.unit.world==world end) end
  wait(player); player().keyLeft=true; wait(function() return player().unit.x<970 end); player().keyLeft=false; D.sleep(0.4)
  world:getChildByTag("trainingTerminal"):emit("Tapped",1); wait(function() return D.Director.ui3D:getChildByTag("training-controls") end)
  local ui=D.Director.ui3D:getChildByTag("training-controls"); ui:getChildByTag("training-switch"):emit("Tapped")
  wait(function() local u=D.Director.ui3D:getChildByTag("training-controls"); return u and u~=ui and u.arena.character.id=="wuyun" end)
  ui=D.Director.ui3D:getChildByTag("training-controls"); local a=ui.arena; assert(a.adopted.sampleCount==18 and #a.recorder.samples==0)
  ui:getChildByTag("training-menu"):getChildByTag("成果复战"):emit("Tapped")
  wait(function() return a.evaluation and a.evaluation.adoptedReplay and not a.evaluating end,160)
  local report=a.evaluation.summary.candidate
  assert(not a.candidate and #a.recorder.samples==0)
  assert(report.wins==3 and report.fallback==0 and report.actions.melee and report.actions.laser and report.actions.fmove)
  assert(D.json.encode(D.DB:query("SELECT slot,payload FROM lsd.Game0Training ORDER BY slot"),false,true)==niBefore)
  assert(D.json.encode(D.DB:query("SELECT slot,payload FROM lsd.Game0Training_wuyun ORDER BY slot"),false,true)==wBefore)
  local nav=0; D.Director.ui3D.children:each(function(n) if n.tag=="academy-navigation" then nav=nav+1 end end)
  assert(nav==0,"Startup navigation leaked into training")
  return "PASS actualStartContinue=true separateNiSixWuyunEighteen=true physicalTrainingTerminal=true publicSwitch=true publicAdoptedReplay=true noRetraining=true savedNativeTreeExecuted=true independentRowsUnchanged=true noStaleAcademyUi=true report="..D.json.encode(report)
 end,debug.traceback)
 local report="LSD_WUYUN_RESUME_"..(ok and result or "FAIL "..tostring(result)).." runId="..id; print(report); D.Content:save(out,report.."\n")
end)
