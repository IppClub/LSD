-- Mission lifecycle / idempotence, independently from the battle outcome test.
local D=require("Dora")
local root=D.Path:getPath(D.Path:getScriptPath(...)); D.Content:insertSearchPath(1,D.Path(root,"Script"))
local output=D.Path(root,"Test","mission-service-result.txt")
local runId=tostring(os.time()); D.Content:save(output,"LSD_MISSION_SERVICE_RUNNING runId="..runId.."\n")
local database=D.Path(D.Content.writablePath,"lsd-mission-service-qa-"..runId..".db")
assert(not D.Content:exist(database) and not D.DB:existDB("lsd"))
assert(D.DB:exec("ATTACH DATABASE '"..database:gsub("'","''").."' AS lsd")>=0)
D.Director.entry:slot("Cleanup",function() if D.DB:existDB("lsd") then D.DB:exec("DETACH DATABASE lsd") end end)
D.thread(function()
 local ok,result=xpcall(function()
  local Service=require("Mission.Service"); local service=assert(Service.open())
  local model={schemaVersion=1,featureSchemaVersion=1,actionSetVersion=1,characterId="ninilite",actions={"laser","fmove","bmove","idle"},sampleCount=7,trainingAccuracy=1,rules={{conditions={},action="laser"}}}
  assert(service:formation().learner=="ninilite")
  assert(service:saveFormationAsync({mentor=true}))
  assert(not assert(Service.open()):formation().learner,"Formation exclusion not persisted")
  assert(service:saveFormationAsync({mentor=true,learner="ninilite"}))
  assert(assert(Service.open()):formation().learner=="ninilite")
  local formation={mentor=true,learner="ninilite"}
  assert(not service:beginAsync("c0-m01",nil,formation),"Untrained team deployed")
  assert(not service:beginAsync("c0-m01",model,{mentor=true}),"Empty formation deployed")
  local a=assert(service:beginAsync("c0-m01",model,formation))
  assert(not service:beginAsync("c0-m01",model,formation),"Second active mission accepted")
  model.rules[1].action="idle"; assert(a.model.rules[1].action=="laser","Deployed model changed with source")
  assert(service:finishAsync(a,"failed",{reason="QA lifecycle failure"}))
  assert(not service:summary().unlocks["library-lead"],"Failure granted reward")
  assert(not service:finishAsync(a,"won",{}),"Terminal status overwritten")
  local b=assert(service:beginAsync("c0-m01",model,formation))
  assert(D.DB:exec("CREATE TRIGGER lsd.fail_mission_reward BEFORE INSERT ON Game0MissionUnlocks BEGIN SELECT RAISE(ABORT,'QA reward fault'); END")>=0)
  assert(not service:finishAsync(b,"won",{}),"Reward fault committed result")
  assert(service:summary().last.status=="active","Reward failure escaped rollback")
  D.DB:exec("DROP TRIGGER lsd.fail_mission_reward")
  assert(service:finishAsync(b,"won",{})); assert(service:finishAsync(b,"won",{}))
  local c=assert(service:beginAsync("c0-m01",model,formation)); assert(service:finishAsync(c,"won",{}))
  assert(#D.DB:query("SELECT id FROM lsd.Game0MissionUnlocks")==1,"Replay duplicated unlock")
  local d=assert(service:beginAsync("c0-m01",model,formation)); assert(service:recoverAsync())
  assert(service:summary().last.status=="aborted","Interrupted mission not recovered safely")
  assert(service:summary().unlocks["library-lead"],"Recovery erased completed progress")
  D.DB:exec("UPDATE lsd.Game0MissionMeta SET schemaVersion=2 WHERE id=1")
  local newer,err=Service.open(); assert(not newer and err=="INCOMPATIBLE_MISSION_SAVE")
  return "PASS formationSaved=true formationGate=true modelSnapshot=true terminalConflict=true atomicReward=true replayOnce=true interruptedSafe=true futureReadOnly=true"
 end,debug.traceback)
 local report="LSD_MISSION_SERVICE_"..(ok and result or "FAIL "..tostring(result)).." runId="..runId
 print(report); D.Content:save(output,report.."\n")
end)
