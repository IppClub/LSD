local S=dofile("Script/Ground/LifeSupport.lua")
local s=S.new(45); s.hp={70,80}; s:update(1,100,300)
assert(s.x==200 and s.active and s.hp[1]==73 and s.hp[2]==83)
local dead=S.new(45); dead.hp={0,70}; dead:update(1,100,300); assert(dead.hp[1]==0 and dead.hp[2]==73,"Life field revived a defeated unit")
local close=s.spent; s:update(1,100,1300); assert(s.spent-close>close,"Separation must increase consumption")
assert(not s:collect("a",12,2000,100,300)); assert(s:collect("a",12,200,100,300)); assert(not s:collect("a",12,200,100,300))
s.gold=0; local hp=s.hp[1]; s:update(1,100,300); assert(not s.active and s.hp[1]==hp-2)
s.gold=30; s:damageMachine(100); hp=s.hp[1]; s:update(1,100,300); assert(not s.active and s.hp[1]==hp-2 and not s:collect("b",12,100,100,300))
local stopped=s.x; s:update(1,500,900); assert(s.x==stopped,"Disabled auxiliary keeps following")
print("LSD_GROUND_SUPPORT_PASS midpoint=true separationCost=true nearHealing=true noHealingRevive=true remoteCollectionRejected=true collectOnce=true depletionHazard=true destroyedMachine=true")

local anchored=S.new(45);anchored.hp={60,80};anchored:update(1,{100,900},nil,{x=100,radius=360})
assert(anchored.x==100 and anchored.radius==360 and anchored.hp[1]==63 and anchored.hp[2]==78 and anchored.hazardDamage==2)
print("LSD_ANCHORED_SUPPORT_PASS fixedRange=true outsideHazard=true nearHealing=true")

-- Defeated bodies keep their role index and HP, without pulling the live field.
local fallen=S.new(45);fallen.hp={0,70,80};fallen:update(1,{10000,100,300})
assert(fallen.x==200 and fallen.span==200 and fallen.radius==190)
assert(fallen.hp[1]==0 and fallen.hp[2]==73 and fallen.hp[3]==83)
assert(math.abs(fallen.spent-.55)<1e-9 and math.abs(fallen.gold-44.45)<1e-9)
local living=S.new(45);living.hp={70,70,80};living:update(1,{10000,100,300})
assert(living.span==9900 and living.spent>fallen.spent,'Living separation lost its actual cost')
fallen.hp={0,0,80};fallen:update(0,{10000,-10000,300});assert(fallen.x==300 and fallen.span==0 and fallen.radius==180 and fallen.hp[1]==0 and fallen.hp[2]==0)
fallen.hp={0,0,0};fallen:update(0,{10000,-10000,400});assert(fallen.x==300 and fallen.span==0,'All-defeated squad pulled the machine')
local fixed=S.new(45);fixed.hp={0,80};fixed:update(1,{10000,100},nil,{x=100,radius=360});assert(fixed.x==100 and fixed.radius==360 and fixed.span==0 and fixed.hp[1]==0 and fixed.hp[2]==83 and math.abs(fixed.spent-.35)<1e-9)
print('LSD_LIVING_SUPPORT_PASS roleIndices=true fallenIgnored=true livingSeparationCharged=true remainingFollower=true noRevive=true allDefeatedStable=true anchored=true')

-- A formation warning uses actual upkeep, never predicts shield attack costs.
local energy=S.new(45);energy.hp={100,100,100};energy:update(0,{100,300,1100})
local estimate=energy:energyObservation();assert(math.abs(estimate.rate-1.35)<1e-9 and estimate.span==1000 and estimate.powered)
local initialGold=energy.gold;energy:update(1,{100,300,1100});assert(math.abs(initialGold-energy.gold-estimate.rate)<1e-9)
energy:update(0,{100,200,300});local gathered=energy:energyObservation();assert(gathered.rate<estimate.rate and gathered.seconds>estimate.seconds)
energy.gold=0;assert(not energy:energyObservation().powered and energy:energyObservation().seconds==0)
energy.gold=45;energy.machineHP=0;assert(not energy:energyObservation().powered and energy:energyObservation().seconds==0)
print('LSD_SUPPORT_ENERGY_WARNING_PASS actualUpkeep=true gatheringExtendsReserve=true stoppedNotPowered=true')
