local T=dofile('Script/Ground/RescueTactics.lua')
local front={range=100,knockX=500};local tail={range=200,knockX=500,rear=true}
local p=T.plan(200,500,nil,0,1000);assert(p.mode=='attack')
p=T.plan(100,500,nil,0,1000);assert(p.mode=='approach'and p.direction==1)
p=T.plan(165,500,nil,0,1000,'approach');assert(p.mode=='approach')
p=T.plan(195,500,nil,0,1000,'approach');assert(p.mode=='attack')
p=T.plan(600,500,{kind='trample',direction=1},0,1000,nil,front);assert(p.mode=='evade'and p.direction==1 and p.face==-1)
p=T.plan(750,500,{kind='trample',direction=1},0,1000,'evade',front);assert(p.mode=='hold'and p.reason=='outside-threat','Retreat must not oscillate back into an active attack')
p=T.plan(400,500,{kind='swing',direction=1},0,1000,nil,tail);assert(p.mode=='evade'and p.direction==-1)
p=T.plan(600,500,{kind='swing',direction=1},0,1000,nil,tail);assert(p.mode=='attack','Tail strike should not repel a safe front target')
p=T.plan(980,900,{kind='trample',direction=1},0,1000,nil,front);assert(p.mode=='hold'and p.reason=='boundary')
p=T.plan(980,1400,nil,0,1000);assert(p.mode=='hold','Out-of-range boundary must not start melee')
p=T.plan(400,500,{kind='rush',direction=1},0,1000,nil,front);assert(p.mode=='evade')
print('RESCUE_TACTICS_PASS hysteresis=true frontalThreat=true rearThreat=true rush=true noOscillation=true boundaries=true')
