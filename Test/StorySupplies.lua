-- Use an earned profile copy; never attach the user's live game database.
local D=require('Dora');local root=D.Path:getPath(D.Path:getScriptPath(...))
D.Content:insertSearchPath(1,D.Path(root,'Script'))
local id=tostring(os.time());local out=D.Path(root,'Test','story-supplies-result.txt')
D.Content:save(out,'LSD_STORY_SUPPLIES_RUNNING '..id..'\n')
D.thread(function()
 local ok,res=xpcall(function()
  local source=assert(D.Content:load(D.Path(root,'Test','pursuit-resume-fixture.txt')))
  assert(D.Path:getPath(source)==D.Content.writablePath and D.Path:getFilename(source):match('^lsd%-pursuit%-qa%-%d+%.db$'))
  local db=D.Path(D.Content.writablePath,'lsd-story-supplies-qa-'..id..'.db')
  assert(not D.DB:existDB('lsd') and not D.Content:exist(db) and D.Content:copyAsync(source,db))
  assert(D.DB:exec("ATTACH DATABASE '"..db:gsub("'","''").."' AS lsd")>=0)
  D.Director.entry:slot('Cleanup',function() if D.DB:existDB('lsd') then D.DB:exec('DETACH DATABASE lsd') end end)
  require('Data.Config'):loadAsync();local S=require('Story.Supplies');local story=assert(require('Story.Service').open())
  assert(story:summary().completed['lin-investigation'])
  for _,recipient in ipairs({'mentor','ninilite','wuyun'}) do
   for _,item in ipairs({'first-aid-water','medicated-plaster'}) do assert(S.count(recipient,item)==1,'Earned supply missing') end
  end
  assert(not S.consumeAsync('unknown','first-aid-water'))
  assert(not S.consumeAsync('mentor','unknown'))
  assert(D.DB:exec("CREATE TRIGGER lsd.fail_medicine BEFORE UPDATE ON Game0StorySupplies BEGIN SELECT RAISE(ABORT,'QA medicine save fault'); END")>=0)
  local consumed,err=S.consumeAsync('mentor','first-aid-water');assert(not consumed and err=='SAVE_FAILED')
  assert(S.count('mentor','first-aid-water')==1,'Failed write consumed stock')
  assert(D.DB:exec('DROP TRIGGER lsd.fail_medicine')>=0)
  assert(S.consumeAsync('mentor','first-aid-water'));assert(S.count('mentor','first-aid-water')==0)
  consumed,err=S.consumeAsync('mentor','first-aid-water');assert(not consumed and err=='EMPTY')
  assert(story:completeAsync('lin-investigation','OuterHeaven',true))
  assert(S.count('mentor','first-aid-water')==0,'Replay replenished consumed medicine')
  assert(require('Story.Service').open());assert(S.count('mentor','first-aid-water')==0)
  assert(S.count('mentor','medicated-plaster')==1 and S.count('ninilite','first-aid-water')==1 and S.count('wuyun','first-aid-water')==1)
  local before=D.json.encode(D.DB:query('SELECT * FROM lsd.Game0StorySupplies ORDER BY source,recipient,item'),false,true)
  D.DB:exec('UPDATE lsd.Game0StoryMeta SET schemaVersion=2 WHERE id=1')
  consumed,err=S.consumeAsync('wuyun','first-aid-water');assert(not consumed and err=='INCOMPATIBLE_STORY_SAVE')
  assert(before==D.json.encode(D.DB:query('SELECT * FROM lsd.Game0StorySupplies ORDER BY source,recipient,item'),false,true))
  return 'PASS earnedSixSupplies=true invalidRejected=true saveFaultNoConsumption=true actualDecrement=true emptyRejected=true replayNoRefill=true reopenedStock=true separateRecipients=true futureReadOnly=true'
 end,debug.traceback)
 local report='LSD_STORY_SUPPLIES_'..(ok and res or 'FAIL '..tostring(res))..' runId='..id
 print(report);D.Content:save(out,report..'\n')
end)
