-- Real SQLite/JSON persistence and fault injection in a fresh isolated DB.
local D = require("Dora")
local root = D.Path:getPath(D.Path:getScriptPath(...))
D.Content:insertSearchPath(1,D.Path(root,"Script"))
local reportPath = D.Path(root,"Test","training-store-result.txt")
local runId = tostring(os.time())
D.Content:save(reportPath,"LSD_TRAINING_STORE_RUNNING runId="..runId.."\n")
local database = D.Path(D.Content.writablePath,"lsd-training-store-qa-"..runId..".db")
assert(not D.Content:exist(database),"QA database collision")
assert(not D.DB:existDB("lsd"),"Another game owns the schema")
local function attach() assert(D.DB:exec("ATTACH DATABASE '"..database:gsub("'","''").."' AS lsd")) end
attach()
D.Director.entry:slot("Cleanup",function() if D.DB:existDB("lsd") then D.DB:exec("DETACH DATABASE lsd") end end)
D.thread(function()
	local ok,result = xpcall(function()
		local Store = require("Training.Store")
		local function model(action)
			return {schemaVersion=1,featureSchemaVersion=1,actionSetVersion=1,characterId="ninilite",actions={"laser","fmove","bmove","idle"},sampleCount=7,trainingAccuracy=1,rules={{conditions={},action=action}}}
		end
		local a,b,c = model("laser"),model("fmove"),model("bmove")
		local store = assert(Store.open())
		assert(not store:saveAsync(a),"Unloaded store overwrote data")
		local empty,status = store:load(); assert(not empty and status=="NEW_PROFILE")
		assert(store:saveAsync(a))
		assert(store:saveAsync(b,a))
		assert(D.DB:exec("DETACH DATABASE lsd")); attach()
		store = assert(Store.open())
		local saved = assert(store:load())
		assert(saved.revision==2 and saved.adopted.rules[1].action=="fmove" and saved.previous.rules[1].action=="laser","Reconnect lost adopted/previous models")
		local before = D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='backup'")[1][1]
		assert(D.DB:exec("CREATE TRIGGER lsd.fail_training_write BEFORE INSERT ON Game0Training WHEN NEW.slot='main' BEGIN SELECT RAISE(ABORT,'QA forced write failure'); END"))
		assert(not store:saveAsync(c,b),"Injected write failure committed")
		assert(store.revision==2 and store.goodEnvelope.adopted.rules[1].action=="fmove","Failed transaction changed cache")
		assert(D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='backup'")[1][1]==before,"Backup update escaped rollback")
		assert(D.DB:exec("DROP TRIGGER lsd.fail_training_write"))
		assert(D.DB:exec("UPDATE lsd.Game0Training SET payload='{broken json' WHERE slot='main'"))
		store = assert(Store.open())
		local recovered,recovery = store:load()
		assert(recovery=="RECOVERED_BACKUP" and recovered.adopted.rules[1].action=="laser","Corrupt main failed recovery")
		assert(store:saveAsync(c,recovered.adopted))
		assert(D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='quarantine'")[1][1]=="{broken json","Damaged primary was not preserved")
		store = assert(Store.open()); saved = assert(store:load())
		assert(saved.adopted.rules[1].action=="bmove" and saved.previous.rules[1].action=="laser","Recovery save damaged valid history")
  local range=model("laser"); range.featureSchemaVersion=2
  range.rules={{conditions={{name="distanceBand",op="==",value="mid"}},action="laser"}}
  assert(store:saveAsync(range,c),"Version 2 model not saved")
  store=assert(Store.open()); local rangeSaved=assert(store:load())
  assert(not store.writeBlocked and rangeSaved.adopted.featureSchemaVersion==2 and rangeSaved.previous.featureSchemaVersion==1,"Mixed feature versions not restored")
  assert(store:saveAsync(c,range),"Version 2 flagged as future after reload")
  local unknown=model("laser"); unknown.featureSchemaVersion=99
  local unknownPayload=D.json.encode({schemaVersion=1,revision=5,adopted=unknown})
  assert(D.DB:exec("UPDATE lsd.Game0Training SET payload=? WHERE slot='main'",{{unknownPayload}})>=0)
  store=assert(Store.open()); store:load()
  local rejected,reason=store:saveAsync(a)
  assert(not rejected and reason=="INCOMPATIBLE_SAVE_READ_ONLY" and D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='main'")[1][1]==unknownPayload,"Unknown features overwritten")
		local future = D.json.encode({schemaVersion=2,revision=5,adopted=a})
		assert(D.DB:exec("UPDATE lsd.Game0Training SET payload=? WHERE slot='main'",{{future}}))
		store = assert(Store.open()); store:load()
		local success,why = store:saveAsync(b,a)
		assert(not success and why=="INCOMPATIBLE_SAVE_READ_ONLY","Future save overwritten")
		assert(D.DB:query("SELECT payload FROM lsd.Game0Training WHERE slot='main'")[1][1]==future)
		assert(D.DB:exec("DROP TABLE lsd.Game0Training")>=0)
		assert(D.DB:exec("PRAGMA query_only=ON")>=0)
		local invalid, schemaError = Store.open()
		D.DB:exec("PRAGMA query_only=OFF")
		assert(not invalid and schemaError=="SCHEMA_FAILED","Failed table creation accepted")
		return "PASS reconnect=true atomicRollback=true backupRecovery=true quarantine=true futureReadOnly=true legacyFeatureOne=true rangeFeatureTwo=true mixedVersions=true unknownFeatureReadOnly=true schemaFailure=true"
	end,debug.traceback)
	local report = "LSD_TRAINING_STORE_"..(ok and result or "FAIL "..tostring(result)).." runId="..runId
	print(report); D.Content:save(reportPath,report.."\n")
end)
